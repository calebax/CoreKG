-- 支付记录表，公共服务中的表
CREATE TABLE IF NOT EXISTS `sale_payment_record` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `order_id` bigint unsigned NOT NULL COMMENT '订单ID',
  `order_sn` varchar(64) DEFAULT NULL COMMENT '订单号（冗余字段，便于查询）',
  `company_id` bigint unsigned DEFAULT NULL COMMENT '公司ID（冗余字段，便于查询）',
  `uin` bigint unsigned DEFAULT NULL COMMENT '用户ID（冗余字段，便于查询）',
  `record_sn` varchar(64) NOT NULL COMMENT '支付记录号',
  `record_type` varchar(16) NOT NULL COMMENT '记录类型：payment-支付，refund-退款',
  `business_source` varchar(32) DEFAULT NULL COMMENT '业务来源，knowledge：知识引擎',
  `amount` bigint unsigned NOT NULL DEFAULT '0' COMMENT '金额（分）',
  `payment_channel` varchar(32) DEFAULT NULL COMMENT '支付渠道：alipay-支付宝，wechat-微信，bank-银行转账等',
  `trade_id` varchar(128) DEFAULT NULL COMMENT '三方交易ID',
  `trade_no` varchar(128) DEFAULT NULL COMMENT '三方交易号',
  `status` varchar(16) NOT NULL DEFAULT 'pending' COMMENT '流水状态：pending-处理中，success-成功，failed-失败',
  `paid_at` datetime(3) DEFAULT NULL COMMENT '支付时间',
  `request_params` text DEFAULT NULL COMMENT '调用三方入参（JSON格式）',
  `response_data` text DEFAULT NULL COMMENT '调用三方出参（JSON格式）',
  `callback_data` text DEFAULT NULL COMMENT '支付回调信息（JSON格式）：以最后一次回调内容为准',
  `remark` varchar(512) DEFAULT NULL COMMENT '备注',
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
  `deleted_at` datetime(3) DEFAULT NULL COMMENT '删除时间, NULL表示未删除',
  PRIMARY KEY (`id`),
  UNIQUE KEY `udx_record_sn` (`record_sn`),
  KEY `idx_deleted_at` (`deleted_at`),
  KEY `idx_order_id` (`order_id`),
  KEY `idx_order_sn` (`order_sn`),
  KEY `idx_company_id` (`company_id`),
  KEY `idx_uin` (`uin`),
  KEY `idx_trade_id` (`trade_id`),
  KEY `idx_no` (`trade_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='支付记录表';
