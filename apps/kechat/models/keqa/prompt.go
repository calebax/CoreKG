package keqa

import "strings"

const roleNamePlaceholder = "{{roleName}}"

func GetKeQAPrompts(roleName string) map[string]string {
	return map[string]string{
		"normal":      strings.ReplaceAll(NormalModePrompt, roleNamePlaceholder, roleName),
		"concise":     strings.ReplaceAll(ConciseEfficientPrompt, roleNamePlaceholder, roleName),
		"study":       strings.ReplaceAll(StudyResearchPrompt, roleNamePlaceholder, roleName),
		"explanation": strings.ReplaceAll(ExplanationReasoningPrompt, roleNamePlaceholder, roleName),
		"formal":      strings.ReplaceAll(FormalRigorousPrompt, roleNamePlaceholder, roleName),
	}
}

